    global.Win11QuizBank = {
        getAllQuestions: function () {
            return QUIZ_BANK.slice();
        },
        getQuestionsForTask: function (taskId) {
            var tid = Number(taskId);
            return QUIZ_BANK.filter(function (q) {
                return Number(q.taskId) === tid;
            });
        },
        getQuestionById: function (qId) {
            for (var i = 0; i < QUIZ_BANK.length; i++) {
                if (QUIZ_BANK[i].id === qId) return QUIZ_BANK[i];
            }
            return null;
        },
        addQuestion: function (qObj) {
            if (!qObj) return { ok: false };
            if (!qObj.id) {
                qObj.id = 'q_' + Date.now() + '_' + Math.floor(Math.random() * 1000);
            }
            var existing = this.getQuestionById(qObj.id);
            if (existing) {
                for (var k in qObj) {
                    if (Object.prototype.hasOwnProperty.call(qObj, k)) existing[k] = qObj[k];
                }
            } else {
                QUIZ_BANK.push(qObj);
            }
            return { ok: true, question: qObj };
        },
        toggleQuestionEnabled: function (id, state) {
            var q = this.getQuestionById(id);
            if (q) {
                q.enabled = (state !== undefined) ? !!state : !q.enabled;
                return true;
            }
            return false;
        },
        deleteQuestion: function (id) {
            for (var i = 0; i < QUIZ_BANK.length; i++) {
                if (QUIZ_BANK[i].id === id) {
                    QUIZ_BANK.splice(i, 1);
                    return true;
                }
            }
            return false;
        }
    };
