    /**
     * Get questions for a specific task.
     * @param {number} taskId 
     * @returns {Array} Array of question objects
     */
    function getQuestionsForTask(taskId) {
        var idNum = Number(taskId);
        var res = [];
        for (var i = 0; i < QUIZ_BANK.length; i++) {
            if (QUIZ_BANK[i].taskId === idNum && QUIZ_BANK[i].enabled !== false) {
                res.push(QUIZ_BANK[i]);
            }
        }
        return res;
    }

    /**
     * Retrieve question by ID.
     */
    function getQuestionById(qId) {
        for (var i = 0; i < QUIZ_BANK.length; i++) {
            if (QUIZ_BANK[i].id === qId) return QUIZ_BANK[i];
        }
        return null;
    }

    /**
     * Get all questions.
     */
    function getAllQuestions() {
        return QUIZ_BANK;
    }

    /**
     * Add a custom question (e.g. from Teacher Panel).
     */
    function addQuestion(qData) {
        if (!qData || !qData.taskId || !qData.questionAr || !qData.correctAnswerAr) {
            return { ok: false, error: 'بيانات السؤال غير مكتملة' };
        }
        var newId = 'custom_' + Date.now() + '_' + Math.floor(Math.random() * 1000);
        var qObj = {
            id: newId,
            taskId: Number(qData.taskId),
            titleAr: qData.titleAr || ('سؤال مخصص للمهمة ' + qData.taskId),
            questionAr: String(qData.questionAr).trim(),
            correctAnswerAr: String(qData.correctAnswerAr).trim(),
            distractorsAr: Array.isArray(qData.distractorsAr) ? qData.distractorsAr : [],
            hintAr: qData.hintAr ? String(qData.hintAr).trim() : 'راجع خطوات النشاط العملي وتفاصيل الإعدادات بعناية.',
            enabled: qData.enabled !== false,
            isCustom: true
        };
        QUIZ_BANK.push(qObj);
        return { ok: true, question: qObj };
    }

    /**
     * Delete question by ID.
     */
    function deleteQuestion(qId) {
        for (var i = 0; i < QUIZ_BANK.length; i++) {
            if (QUIZ_BANK[i].id === qId) {
                QUIZ_BANK.splice(i, 1);
                return true;
            }
        }
        return false;
    }

    /**
     * Toggle enabled state of a question.
     */
    function toggleQuestionEnabled(qId, isEnabled) {
        var q = getQuestionById(qId);
        if (q) {
            q.enabled = !!isEnabled;
            return true;
        }
        return false;
    }

    global.Win11QuizBank = {
        getAllQuestions: getAllQuestions,
        getQuestionsForTask: getQuestionsForTask,
        getQuestionById: getQuestionById,
        addQuestion: addQuestion,
        deleteQuestion: deleteQuestion,
        toggleQuestionEnabled: toggleQuestionEnabled
    };

